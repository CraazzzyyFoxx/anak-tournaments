// Regenerates e2e/support/route-table.ts from the gateway's edge.RouteSpec
// literals — the only place a route's Auth mode is declared.
//
//   cd frontend && bun e2e/scripts/gen-route-table.ts
//
// Fails when cmd/gateway/main.go registers a mux.HandleFunc route that no
// RouteSpec table (or *DocRoutes mirror) declares: such a route has no Auth
// classification to test against.
import fs from "node:fs";
import path from "node:path";

const GATEWAY = path.join(import.meta.dirname, "..", "..", "..", "gateway");
const OUT = path.join(import.meta.dirname, "..", "support", "route-table.ts");

const AUTH = { AuthNone: "none", AuthOptional: "optional", AuthRequired: "required" } as const;
const STATUS: Record<string, number> = { StatusOK: 200, StatusCreated: 201, StatusAccepted: 202, StatusNoContent: 204 };

type Row = { method: string; pattern: string; auth: string; success: number; table: string };

function goFiles(dir: string): string[] {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) return goFiles(p);
    return e.name.endsWith(".go") && !e.name.endsWith("_test.go") ? [p] : [];
  });
}

const routes = new Map<string, Row>();
for (const file of goFiles(path.join(GATEWAY, "internal"))) {
  const pkg = path.basename(path.dirname(file));
  let table = "";
  for (const line of fs.readFileSync(file, "utf8").split("\n")) {
    table = line.match(/^var (\w+) = /)?.[1] ?? table;
    const m = line.match(/\{Method: "([A-Z]+)", Pattern: "([^"]+)"/);
    if (!m) continue;
    const auth = AUTH[(line.match(/Auth: edge\.(\w+)/)?.[1] ?? "AuthNone") as keyof typeof AUTH];
    const s = line.match(/Success: (?:http\.)?(\w+)/)?.[1];
    const row = { method: m[1], pattern: m[2], auth, success: s ? (STATUS[s] ?? Number(s)) : 200, table: `${pkg}.${table}` };
    const key = `${row.method} ${row.pattern}`;
    const seen = routes.get(key);
    if (seen && (seen.auth !== row.auth || seen.success !== row.success)) {
      throw new Error(`${key}: ${seen.table} and ${row.table} disagree on auth/success`);
    }
    // Keep the registering table over its *DocRoutes mirror.
    if (!seen || seen.table.endsWith("DocRoutes")) routes.set(key, row);
  }
}

const main = fs.readFileSync(path.join(GATEWAY, "cmd", "gateway", "main.go"), "utf8");
const unclassified = [...main.matchAll(/mux\.HandleFunc\("([A-Z]+) (\/api\/v1\/[^"]+)"/g)]
  .map((m) => `${m[1]} ${m[2]}`)
  .filter((key) => !routes.has(key));
if (unclassified.length) {
  throw new Error(`main.go routes with no RouteSpec/DocRoutes entry (add one so Auth is declared):\n${unclassified.join("\n")}`);
}

const rows = [...routes.values()].sort((a, b) => a.pattern.localeCompare(b.pattern) || a.method.localeCompare(b.method));
fs.writeFileSync(
  OUT,
  `// GENERATED by e2e/scripts/gen-route-table.ts from gateway/internal/**/*.go — do not edit.\n` +
    `export type Auth = "none" | "optional" | "required";\n` +
    `export type Route = { method: string; pattern: string; auth: Auth; success: number; table: string };\n\n` +
    `export const ROUTES: Route[] = [\n${rows.map((r) => `  ${JSON.stringify(r)},`).join("\n")}\n];\n`
);
console.log(`${rows.length} routes -> ${path.relative(process.cwd(), OUT)}`);
