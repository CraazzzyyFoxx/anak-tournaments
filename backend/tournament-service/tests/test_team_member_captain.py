"""Every seat writer snapshots its team's captain (spec §7.3). Needs the test Postgres.

A tournament seat takes it from ``Team.captain_id`` when the seat is filled; a seat that moves (a slot swap, an
advancement) carries the flag it was filled with, because the move re-reads the snapshot rather than the team. The
moves below hand the captaincy to another member first, so a writer that re-read the team would get it wrong.
"""

from __future__ import annotations

import sqlalchemy as sa

from shared.core import enums
from shared.models.encounter import EncounterTeam, EncounterTeamMember
from shared.models.tournament.stage import StageItem, StageItemInput
from shared.models.tournament.team import Player, Team
from shared.services.encounter.participants import active_teams
from shared.services.encounter.result import apply_result, lock_encounter
from shared.tests.encounter_writer_case import EncounterWriterCase
from src import schemas
from src.services.admin.encounter import encounter_service
from src.services.admin.stage import stage_service
from src.services.bracket import advancement


class TeamMemberCaptainTests(EncounterWriterCase):
    """team0 fields m0 (its captain) and m1; team1 fields m2 and m3 and has no captain."""

    async def asyncSetUp(self) -> None:
        await super().asyncSetUp()
        async with self.Session() as s:
            # ``captain_id`` is a ``players.user`` id: m0's player.
            (await s.get_one(Team, self.ids["team0"])).captain_id = self.users[0]
            for key, team in (("m0", "team0"), ("m1", "team0"), ("m2", "team1"), ("m3", "team1")):
                s.add(
                    Player(
                        name=key,
                        rank=2500,
                        tournament_id=self.ids["t"],
                        team_id=self.ids[team],
                        workspace_member_id=self.ids[key],
                    )
                )
            await s.commit()

    async def _generate(self) -> list[int]:
        """A four-team single elimination, generated by the admin service; its encounter ids."""
        async with self.Session() as s:
            stage = await stage_service.create_stage(
                s,
                self.ids["t"],
                schemas.StageCreate(name="Playoff", stage_type=enums.StageType.SINGLE_ELIMINATION, order=1),
            )
            item = StageItem(stage_id=stage.id, name="A", type=enums.StageItemType.GROUP, order=0)
            s.add(item)
            await s.flush()
            for slot in range(1, 5):
                s.add(
                    StageItemInput(
                        stage_item_id=item.id,
                        slot=slot,
                        input_type=enums.StageItemInputType.FINAL,
                        team_id=self.ids[f"team{slot - 1}"],
                    )
                )
            await s.commit()
        # A fresh session: this one still holds the stage with the item list it was created with.
        async with self.Session() as s:
            return [encounter.id for encounter in await stage_service.generate_encounters(s, stage.id, notify=False)]

    async def _hand_captaincy_to_m1(self) -> None:
        async with self.Session() as s:
            (await s.get_one(Team, self.ids["team0"])).captain_id = self.users[1]
            await s.commit()

    async def _seats(self, encounter_ids: list[int]) -> list[tuple[int, int, int, bool]]:
        """``(encounter, slot, workspace member, captain)`` of every live seat's stored snapshot."""
        async with self.Session() as s:
            rows = await s.execute(
                sa.select(
                    EncounterTeam.encounter_id,
                    EncounterTeam.slot,
                    EncounterTeamMember.workspace_member_id,
                    EncounterTeamMember.is_captain,
                )
                .join(EncounterTeam, EncounterTeam.id == EncounterTeamMember.encounter_team_id)
                .where(EncounterTeamMember.encounter_id.in_(encounter_ids), EncounterTeamMember.active.is_(True))
            )
            return [tuple(row) for row in rows]

    async def _seat_of_m0(self, encounter_ids: list[int]) -> tuple[int, int]:
        """``(encounter, slot)`` of m0's first live seat: team0's opening match."""
        rows = await self._seats(encounter_ids)
        return next((encounter, slot) for encounter, slot, member, _ in rows if member == self.ids["m0"])

    async def test_a_generated_seat_takes_its_captain_from_the_team(self) -> None:
        encounters = await self._generate()

        self.assertEqual(
            {self.ids["m0"]: True, self.ids["m1"]: False, self.ids["m2"]: False, self.ids["m3"]: False},
            {member: captain for _, _, member, captain in await self._seats(encounters)},
        )

    async def test_a_swapped_seat_keeps_the_captain_it_was_filled_with(self) -> None:
        encounters = await self._generate()
        await self._hand_captaincy_to_m1()
        encounter, slot = await self._seat_of_m0(encounters)

        async with self.Session() as s:
            await encounter_service.swap_slots(
                s,
                encounter,
                schemas.EncounterSwapSlotInput(slot=slot, target_encounter_id=encounter, target_slot=3 - slot),
            )

        self.assertEqual(
            {(encounter, 3 - slot, self.ids["m0"], True), (encounter, 3 - slot, self.ids["m1"], False)},
            {row for row in await self._seats(encounters) if row[2] in (self.ids["m0"], self.ids["m1"])},
        )

    async def test_an_advanced_seat_keeps_the_captain_it_was_filled_with(self) -> None:
        encounters = await self._generate()
        await self._hand_captaincy_to_m1()
        semi_id, slot = await self._seat_of_m0(encounters)

        async with self.Session() as s:
            semi = await lock_encounter(s, semi_id)
            seats = await active_teams(s, semi_id)
            await apply_result(
                s,
                semi,
                source=enums.EncounterResultSource.ADMIN,
                totals={seat.id: (1.0 if seat.slot == slot else 0.0) for seat in seats},
                placements={seat.id: (1 if seat.slot == slot else 2) for seat in seats},
                action=enums.EncounterResultAuditAction.CONFIRM,
                audit_source="admin",
                actor_user_id=self.users[0],
                reason="test",
            )
            outcome = await advancement.advance_after_result(s, semi)
            await s.commit()

        self.assertEqual(1, len(outcome.placed))
        final_id = outcome.placed[0][0]
        self.assertEqual(
            {self.ids["m0"]: True, self.ids["m1"]: False},
            {
                member: captain
                for encounter, _, member, captain in await self._seats(encounters)
                if encounter == final_id
            },
        )
